#!/usr/bin/env python3
"""Propage le registre des entrées (backend/app/inputs/bindings.py) vers le frontend."""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parents[2]
FRONTEND_TS = REPO_DIR / "frontend" / "src" / "lib" / "remoteBindings.generated.ts"
REGISTRY_PATH = REPO_DIR / "backend" / "app" / "inputs" / "bindings.py"


def load_registry():
    spec = importlib.util.spec_from_file_location("bobine_remote_bindings", REGISTRY_PATH)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def render_frontend_ts(registry) -> str:
    actions = ", ".join(json.dumps(action) for action in registry.REMOTE_ACTIONS)
    rows = "".join(
        f"  {json.dumps(source)}: [{', '.join(json.dumps(a) for a in chain)}],\n"
        for source, chain in registry.DEFAULT_BINDINGS.items()
    )
    directions = ", ".join(f"{button}: {json.dumps(action)}" for button, action in registry.GAMEPAD_DIRECTIONS.items())
    triggers = ", ".join(str(button) for button in registry.ANALOG_TRIGGERS)
    return (
        "// Generated by scripts/generators/sync_remote_bindings.py.\n"
        f"export const REMOTE_ACTIONS = [{actions}] as const;\n"
        f"export const GAMEPAD_DIRECTIONS = {{ {directions} }} as const;\n"
        f"export const ANALOG_TRIGGERS = [{triggers}] as const;\n"
        f"export const DEFAULT_REMOTE_BINDINGS: Readonly<Record<string, readonly (typeof REMOTE_ACTIONS)[number][]>> = {{\n{rows}}};\n"
    )


def outputs() -> dict[Path, str]:
    return {FRONTEND_TS: render_frontend_ts(load_registry())}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="échoue si un fichier généré est absent ou périmé")
    args = parser.parse_args(argv)
    expected = outputs()
    if args.check:
        stale = [p for p, text in expected.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"périmé : {path.relative_to(REPO_DIR)} — relancer scripts/generators/sync_remote_bindings.py", file=sys.stderr)
        return 1 if stale else 0
    for path, text in expected.items():
        path.write_text(text, encoding="utf-8")
        print(f"écrit : {path.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
